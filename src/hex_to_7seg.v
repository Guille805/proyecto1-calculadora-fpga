module hex_to_7seg (
    input  wire [3:0] hex,
    output wire [6:0] seg
);

    wire n0;
    wire n1;
    wire n2;
    wire n3;

    wire m0;
    wire m1;
    wire m2;
    wire m3;
    wire m4;
    wire m5;
    wire m6;
    wire m7;
    wire m8;
    wire m9;
    wire m10;
    wire m11;
    wire m12;
    wire m13;
    wire m14;
    wire m15;


    // -------------------------------------------------
    // Inversión de bits de entrada
    // -------------------------------------------------

    not (n0, hex[0]);
    not (n1, hex[1]);
    not (n2, hex[2]);
    not (n3, hex[3]);


    // -------------------------------------------------
    // Decodificación de las 16 entradas posibles
    // -------------------------------------------------

    // 0000 = 0
    and (m0, n3, n2, n1, n0);

    // 0001 = 1
    and (m1, n3, n2, n1, hex[0]);

    // 0010 = 2
    and (m2, n3, n2, hex[1], n0);

    // 0011 = 3
    and (m3, n3, n2, hex[1], hex[0]);

    // 0100 = 4
    and (m4, n3, hex[2], n1, n0);

    // 0101 = 5
    and (m5, n3, hex[2], n1, hex[0]);

    // 0110 = 6
    and (m6, n3, hex[2], hex[1], n0);

    // 0111 = 7
    and (m7, n3, hex[2], hex[1], hex[0]);

    // 1000 = 8
    and (m8, hex[3], n2, n1, n0);

    // 1001 = 9
    and (m9, hex[3], n2, n1, hex[0]);

    // 1010 = A
    and (m10, hex[3], n2, hex[1], n0);

    // 1011 = b
    and (m11, hex[3], n2, hex[1], hex[0]);

    // 1100 = C
    and (m12, hex[3], hex[2], n1, n0);

    // 1101 = d
    and (m13, hex[3], hex[2], n1, hex[0]);

    // 1110 = E
    and (m14, hex[3], hex[2], hex[1], n0);

    // 1111 = F
    and (m15, hex[3], hex[2], hex[1], hex[0]);


    // -------------------------------------------------
    // Segmento A
    // Encendido para:
    // 0,2,3,5,6,7,8,9,A,C,E,F
    // -------------------------------------------------

    or (
        seg[6],
        m0,
        m2,
        m3,
        m5,
        m6,
        m7,
        m8,
        m9,
        m10,
        m12,
        m14,
        m15
    );


    // -------------------------------------------------
    // Segmento B
    // Encendido para:
    // 0,1,2,3,4,7,8,9,A,d
    // -------------------------------------------------

    or (
        seg[5],
        m0,
        m1,
        m2,
        m3,
        m4,
        m7,
        m8,
        m9,
        m10,
        m13
    );


    // -------------------------------------------------
    // Segmento C
    // Encendido para:
    // 0,1,3,4,5,6,7,8,9,A,b,d
    // -------------------------------------------------

    or (
        seg[4],
        m0,
        m1,
        m3,
        m4,
        m5,
        m6,
        m7,
        m8,
        m9,
        m10,
        m11,
        m13
    );


    // -------------------------------------------------
    // Segmento D
    // Encendido para:
    // 0,2,3,5,6,8,9,b,C,d,E
    // -------------------------------------------------

    or (
        seg[3],
        m0,
        m2,
        m3,
        m5,
        m6,
        m8,
        m9,
        m11,
        m12,
        m13,
        m14
    );


    // -------------------------------------------------
    // Segmento E
    // Encendido para:
    // 0,2,6,8,A,b,C,d,E,F
    // -------------------------------------------------

    or (
        seg[2],
        m0,
        m2,
        m6,
        m8,
        m10,
        m11,
        m12,
        m13,
        m14,
        m15
    );


    // -------------------------------------------------
    // Segmento F
    // Encendido para:
    // 0,4,5,6,8,9,A,b,C,E,F
    // -------------------------------------------------

    or (
        seg[1],
        m0,
        m4,
        m5,
        m6,
        m8,
        m9,
        m10,
        m11,
        m12,
        m14,
        m15
    );


    // -------------------------------------------------
    // Segmento G
    // Encendido para:
    // 2,3,4,5,6,8,9,A,b,d,E,F
    // -------------------------------------------------

    or (
        seg[0],
        m2,
        m3,
        m4,
        m5,
        m6,
        m8,
        m9,
        m10,
        m11,
        m13,
        m14,
        m15
    );

endmodule